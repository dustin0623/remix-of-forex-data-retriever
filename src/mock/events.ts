function atOffset(dayOffset: number, hhmm: string): string {
  const parts = hhmm.split(":").map(Number);
  const d = new Date();
  d.setDate(d.getDate() + dayOffset);
  d.setHours(parts[0] ?? 0, parts[1] ?? 0, 0, 0);
  return d.toISOString();
}

